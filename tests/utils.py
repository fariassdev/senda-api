def assert_course_structure_valid(structure: CourseStructureDTO) -> None:
    """
    Helper function to validate that a CourseStructureDTO is properly formed.

    Args:
        structure: CourseStructureDTO to validate

    Raises:
        AssertionError: If structure is invalid
    """
    # Basic structure checks
    assert structure.title, "Course title should not be empty"
    assert structure.description, "Course description should not be empty"
    assert structure.duration_days > 0, "Duration must be positive"
    assert structure.difficulty_level in [
        DifficultyLevel.BEGINNER,
        DifficultyLevel.INTERMEDIATE,
        DifficultyLevel.ADVANCED,
    ], "Invalid difficulty level"

    # Tags checks
    assert isinstance(structure.tags, list), "Tags should be a list"
    assert len(structure.tags) > 0, "Should have at least one tag"

    # Lessons checks
    assert isinstance(structure.lessons, list), "Lessons should be a list"
    assert len(structure.lessons) > 0, "Should have at least one lesson"

    # Validate each lesson
    for i, lesson in enumerate(structure.lessons):
        assert lesson.title, f"Lesson {i} title should not be empty"
        assert lesson.core_practice, f"Lesson {i} core_practice should not be empty"
        assert lesson.key_point, f"Lesson {i} key_point should not be empty"
        assert lesson.tone, f"Lesson {i} tone should not be empty"
        assert lesson.duration_minutes > 0, f"Lesson {i} duration must be positive"
        assert lesson.order > 0, f"Lesson {i} order must be positive"

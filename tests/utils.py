async def create_another_test_user(
    session: AsyncSession, user_repository: IUserRepository
) -> UserDTO:
    create_user_dto = CreateUserDTO(
        username="temp-user", email="temp-user@gmail.com", password="password"
    )
    return await user_repository.add(session=session, create_item=create_user_dto)


async def create_another_test_course(
    session: AsyncSession, course_repository: ICourseRepository, author_id: int
) -> CourseRecordDTO:
    create_course_dto = CreateCourseDTO(
        title="One More Test Course",
        description="Test Description",
        difficulty_level="Beginner",
        tags=["tag1", "tag2", "tag3"],
    )
    return await course_repository.add(
        session=session, author_id=author_id, create_item=create_course_dto
    )


def create_sample_course_structure(
    title: str = "Sample Generated Course",
    description: str = "A test course generated by AI",
    duration_days: int = 7,
    difficulty_level: DifficultyLevel = DifficultyLevel.BEGINNER,
    num_lessons: int = 3,
) -> CourseStructureDTO:
    """
    Helper function to create a sample CourseStructureDTO for testing.

    Args:
        title: Course title
        description: Course description
        duration_days: Number of days for the course
        difficulty_level: Course difficulty level
        num_lessons: Number of lessons to generate

    Returns:
        CourseStructureDTO with sample data
    """
    lessons = [
        LessonStructureDTO(
            title=f"Day {i + 1}: Lesson {i + 1}",
            core_practice=f"Practice {i + 1}",
            key_point=f"Key point {i + 1}",
            tone="calm",
            duration_minutes=10,
            order=i + 1,
        )
        for i in range(num_lessons)
    ]

    return CourseStructureDTO(
        title=title,
        description=description,
        duration_days=duration_days,
        difficulty_level=difficulty_level,
        tags=["test", "generated"],
        lessons=lessons,
    )


